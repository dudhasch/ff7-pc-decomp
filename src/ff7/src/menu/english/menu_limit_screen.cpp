/*
 * For each of the three party slots, copies the three limit attacks of the character's current
 * level into that slot's stat record. The level comes out of the savemap one-based and is
 * decremented, so `level * 3 + slot` indexes the nine attacks.
 */
// FUNCTION: FF7 0x00703517
void __cdecl Menu_RebuildPartyLimitRecords(void)
{
    int level;
    int slot;
    int i;
    unsigned char *src;
    int actor;

    src = g_LimitMenuDescBlock;
    for (i = 0; i < 3; i++) {
        if (gSavemap.party[i] == PARTY_CHAR_NONE) {
            continue;
        }
        actor = g_CharIdToSaveSlot[gSavemap.party[i]];
        level = gSavemap.chars[actor].limitLevel - 1;
        for (slot = 0; slot < 3; slot++) {
            g_MenuPartyStats[i].limitAttacks[slot] =
                (unsigned char)Kernel_GetLimitAttackId(actor,
                                                       level * 3 + slot);
            memcpy(g_MenuPartyStats[i].limitRecords[slot],
                   src + Kernel_GetLimitAttackId(actor, level * 3 + slot) *
                             28,
                   28);
        }
    }
}
