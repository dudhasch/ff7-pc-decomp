/*
 * Commits entered name and finalizes character recruitment.
 */
// FUNCTION: FF7 0x00719b81
void __cdecl Menu_NameEntryFinishJoiningCharacter(void)
{
    if (g_MenuNameEntryCharId != 9 && g_MenuNameEntryCharId != 0) {
        Kernel_InitJoiningCharacter(
            &gSavemap.chars[g_CharIdToSaveSlot[g_MenuNameEntryCharId]]);
        gSavemap.chars[g_MenuNameEntryCharId].hp =
            gSavemap.chars[g_MenuNameEntryCharId].baseHp;
        gSavemap.chars[g_MenuNameEntryCharId].mp =
            gSavemap.chars[g_MenuNameEntryCharId].baseMp;
    }
    InputConfig_RestoreBackup();
}

/*
 * One frame of the name entry screen, which the field opens with FIELD_REQUEST_NAME_ENTRY; the
 * menu dispatcher passes the request's parameter as `arg`, the character to name. On the first
 * frame it stores the character id, resets the state and frame count and sets the screen up
 * (Menu_NameEntryInit: character 6 or 7 is reset from the kernel template, an id of 0x64 or more
 * becomes 9 with the other portrait set, the default name is loaded and the keyboard switches to
 * its default typing bindings), sets the input auto-repeat to a first delay of 200 and an interval
 * of 50 and the overlay flag. Each frame until the state becomes -1 it runs Menu_NameEntryFrame
 * with the frame count (kept in g_MenuNameEntryFrameCounter), flips g_MenuNameEntryFrameParity and counts
 * on. When the name is done it finishes the join (Menu_NameEntryFinishJoiningCharacter: for ids
 * other than 0 and 9 the character's record is initialised and HP and MP set to their base values;
 * the saved key bindings come back) and sets g_MenuExitRequested.
 */
// FUNCTION: FF7 0x00719c08
void __cdecl Menu_NameEntryModuleUpdate(int arg)
{
    if (g_MenuNameEntryActive == 0) {
        g_MenuNameEntryCharId = arg;
        g_MenuNameEntryFadePhase = MENU_NAME_ENTRY_FADE_IN;
        g_MenuNameEntryFrameCounter = g_MenuNameEntryFadePhase;
        Menu_NameEntryInit();
        g_MenuNameEntryFrameParity = 0;
        Input_SetRepeatRates(0xc8, 50);
        g_MenuOverlayActive = 1;
        g_MenuNameEntryActive = g_MenuOverlayActive;
    }
    if (g_MenuNameEntryFadePhase != MENU_NAME_ENTRY_FADE_DONE && g_MenuNameEntryActive == 1) {
        Menu_NameEntryFrame(g_MenuNameEntryFrameCounter);
        if (g_MenuNameEntryFadePhase == MENU_NAME_ENTRY_FADE_DONE) {
            g_MenuOverlayActive = 0;
            g_MenuNameEntryActive = g_MenuOverlayActive;
        }
        g_MenuNameEntryFrameParity ^= 1;
        g_MenuNameEntryFrameCounter += 1;
    }
    if (g_MenuNameEntryActive != 1 && g_MenuNameEntryFadePhase == MENU_NAME_ENTRY_FADE_DONE) {
        Menu_NameEntryFinishJoiningCharacter();
        g_MenuExitRequested = 1;
    }
}

