/*
 * Types on the name entry screen from the keyboard: for each key-down event below scan code 0x3B
 * that g_MenuNameEntryLayout maps, Space appends a space, Backspace removes the last glyph, and any
 * other key moves the grid cursor to the key's glyph (shifted keys with Shift held, the others
 * without) and appends it.
 */
// FUNCTION: FF7 0x00718710
void __cdecl Menu_DebugHotkeyPoll(void)
{
    unsigned char *pKeyState;
    unsigned char shiftHeld;
    int rowDelta;
    int colOfs;
    unsigned int *keyEventPtr;

    pKeyState = DI_KeyboardGetState();
    rowDelta = 0;
    colOfs = 0;
    do {
        keyEventPtr = (unsigned int *)DI_KeyboardGetNextEvent();
        if (keyEventPtr != 0 && (keyEventPtr[1] & 0x80) != 0 && keyEventPtr[0] < 0x3b) {
            if (pKeyState != 0) {
                shiftHeld = ((pKeyState[DIK_LSHIFT] & 0x80) == 0 &&
                     (pKeyState[DIK_RSHIFT] & 0x80) == 0)
                        ? 0
                        : 1;
            }
            if (g_MenuNameEntryLayout.entries[keyEventPtr[0]].shiftFlags != 0) {
                switch (keyEventPtr[0]) {
                case DIK_SPACE:
                    SfxPreloadAndPlayOnChannel5(SFX_MENU_CURSOR);
                    Menu_NameEntryAppendGlyph(0);
                    break;
                case DIK_BACK:
                    SfxPreloadAndPlayOnChannel5(SFX_MENU_CANCEL);
                    Menu_NameEntryRemoveGlyph();
                    break;
                default:
                    if (shiftHeld != 0 &&
                        (g_MenuNameEntryLayout.entries[keyEventPtr[0]].shiftFlags & 2) != 0) {
                        switch (keyEventPtr[0]) {
                        case DIK_SEMICOLON:
                            rowDelta = -1;
                            colOfs = 0;
                            break;
                        case DIK_EQUALS:
                            rowDelta = 8;
                            colOfs = 2;
                            break;
                        default:
                            rowDelta = 0;
                            colOfs = -3;
                            break;
                        }
                        g_MenuNameEntryCursors.cursor[0].col =
                            g_MenuNameEntryLayout.entries[keyEventPtr[0]].gridCol + rowDelta;
                        g_MenuNameEntryCursors.cursor[0].row =
                            g_MenuNameEntryLayout.entries[keyEventPtr[0]].gridRow + colOfs;
                        SfxPreloadAndPlayOnChannel5(SFX_MENU_CURSOR);
                        Menu_NameEntryAppendGlyph(Menu_GetKeyGridByte(
                            g_MenuNameEntryTargetSlot, g_MenuNameEntryCursors.cursor[0].col,
                            g_MenuNameEntryCursors.cursor[0].row));
                    } else if ((g_MenuNameEntryLayout.entries[keyEventPtr[0]].shiftFlags & 1) != 0 &&
                               shiftHeld == 0) {
                        g_MenuNameEntryCursors.cursor[0].col =
                            g_MenuNameEntryLayout.entries[keyEventPtr[0]].gridCol + rowDelta;
                        g_MenuNameEntryCursors.cursor[0].row =
                            g_MenuNameEntryLayout.entries[keyEventPtr[0]].gridRow + colOfs;
                        SfxPreloadAndPlayOnChannel5(SFX_MENU_CURSOR);
                        Menu_NameEntryAppendGlyph(Menu_GetKeyGridByte(
                            g_MenuNameEntryTargetSlot, g_MenuNameEntryCursors.cursor[0].col,
                            g_MenuNameEntryCursors.cursor[0].row));
                    }
                    break;
                }
            }
        }
    } while (keyEventPtr != 0);
}

