/*
 * Draws the per-face model, spun by g_BattleSpecPetrifyFaceSpinAngles: whole until frame 0x1E, then
 * with each face moved by g_BattleSpecPetrifyBuffer2 and the model tilting over. At frame 0x1E it
 * spawns 24 falling sprites and from then on updates the bouncing particles; it retires at 0x2D.
 */
// FUNCTION: FF7 0x0051d0de
void __cdecl BattleFx_SpecialPetrifyPerFaceOffsetModelTask(void)
{
#pragma pack(push, 1)
    /* Locals by stack slot: see FRAME UNION in lib/codegen.h. */
    union {
        unsigned char storage[92];
        int animIndex;
        struct { unsigned char pad_to_4[0x4]; int paramIndex; };
        struct { unsigned char pad_to_8[0x8]; PsxMatrix spinMatrix; };
        struct { unsigned char pad_to_28[0x28]; int transformMatrix; };
        struct { unsigned char pad_to_3A[0x3A]; int offsetX; };
        struct { unsigned char pad_to_3E[0x3E]; int offsetY; };
        struct { unsigned char pad_to_42[0x42]; int offsetZ; };
        struct { unsigned char pad_to_48[0x48]; BattleFxPetrifyFallingSpriteSlot *fallingSlot; };
        struct { unsigned char pad_to_4C[0x4C]; short spriteIndex; };
        struct { unsigned char pad_to_50[0x50]; BattleFxPetrifyPerFaceOffsetModelSlot *modelSlot; };
        struct { unsigned char pad_to_54[0x54]; short radius; };
        struct { unsigned char pad_to_58[0x58]; short angle; };
    } frame;
#pragma pack(pop)

    frame.modelSlot = (BattleFxPetrifyPerFaceOffsetModelSlot *)BATTLE_CURRENT_TASK_SLOT;
    RotMatrix((SVECTOR *)&g_BattleSpecPetrifyFaceSpinAngles, &frame.transformMatrix);
    ScaleMatrix(&frame.transformMatrix, (int *)&g_BattleSpecPetrifySpriteRequest3);
    frame.offsetX = frame.modelSlot->offsetX;
    frame.offsetY = frame.modelSlot->offsetY;
    frame.offsetZ = frame.modelSlot->offsetZ;
    MultiplyMatrix(&g_BattleCameraTransform, &frame.transformMatrix, &frame.transformMatrix);
    if (frame.modelSlot->frameCounter < 0x1E) {
        SetRotMatrix(&frame.transformMatrix);
        SetTransMatrix(&frame.transformMatrix);
        if (frame.modelSlot->frameCounter < 0x10) {
            frame.paramIndex = frame.modelSlot->frameCounter >> 1;
        } else {
            frame.paramIndex = 7;
        }
        g_BattleSpecPetrifySpriteRequest3.faceOffsetRecord = g_BattleSpecPetrifyFaceOffsets[frame.paramIndex];
        if (frame.modelSlot->frameCounter < 0x10) {
            frame.animIndex = frame.modelSlot->frameCounter >> 1;
        } else {
            frame.animIndex = 7;
        }
        g_BattleSpecPetrifySpriteRequest3.req3Model16 = Gfx_ModelTableGetRenderObject(g_BattleSpecPetrifyAnimData2[frame.animIndex], g_BattleSpecPetrifyLoadedResTable);
        g_BattleSpecPetrifyDrawListHead = BattleFx_SubmitModelDraw((BattleFxModelDraw *)&g_BattleSpecPetrifySpriteRequest3.req3Model16, g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleSpecPetrifyDrawListHead);
    } else {
        g_BattleSpecPetrifySpriteRequest3.req3Word42 = 0x80 - (frame.modelSlot->frameCounter * 8 + -0xF0);
        RotMatrix((SVECTOR *)&g_BattleSpecPetrifyFaceSpinAngles, &frame.spinMatrix);
        RotateMatrixX(frame.modelSlot->frameCounter - 0x1E << 8, &frame.spinMatrix);
        Gfx_SetPsxPrimQuadState(9, 4, (GfxPsxSpriteQuadState *)(Gfx_ModelTableGetSpriteObject(0x11, g_BattleSpecPetrifyLoadedResTable)));
        g_BattleSpecPetrifyDrawListHead = BattleFx_SpecialPetrifyDrawPerFaceOffsetModel((BattleFxFreezeBreathDrawRecord *)&g_BattleSpecPetrifySpriteRequest3.faceOffsetRecord, g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, (BattleFxPetrifyDrawPrim *)g_BattleSpecPetrifyDrawListHead, (struct Vec3sPacked *)&g_BattleSpecPetrifyBuffer2, &frame.transformMatrix, (struct BattleFxOffsetTriMeshDesc *)&frame.spinMatrix);
    }
    if (g_BattleIsPaused != 0) {
        return;
    }
    if (frame.modelSlot->frameCounter == 0x1E) {
        for (frame.spriteIndex = 0; frame.spriteIndex < 0x18; frame.spriteIndex++) {
            frame.fallingSlot = (BattleFxPetrifyFallingSpriteSlot *)BATTLE_NEW_TASK_SLOT(BattleFx_SpecialPetrifyFallingSpriteTask);
            frame.fallingSlot->posX = frame.modelSlot->offsetX;
            frame.fallingSlot->posY = frame.modelSlot->offsetY;
            frame.fallingSlot->posZ = frame.modelSlot->offsetZ;
            frame.angle = (rand() % 4096);
            frame.radius = rand() % 0x190;
            frame.fallingSlot->offsetCos = CosFixed(frame.angle) * frame.radius >> 0xC;
            frame.fallingSlot->offsetSin = SinFixed(frame.angle) * frame.radius >> 0xC;
            frame.fallingSlot->randomVelocity = -rand() % 0x190;
        }
    }
    if (frame.modelSlot->frameCounter >= 0x1E) {
        BattleFx_SpecialPetrifyUpdateBouncingParticles();
    }
    (frame.modelSlot->frameCounter)++;
    if (frame.modelSlot->frameCounter == 0x2D) {
        frame.modelSlot->ownerSlot = BATTLE_TASK_FREE;
    }
}

/*
 * Draws a model face by face, first its textured triangles, then its shaded ones: each face is
 * centered on its centroid, moved by the matching entry of faceOffsets and transformed by matrix
 * before its primitive is emitted.
 */
// FUNCTION: FF7 0x0051d3e4
int __cdecl BattleFx_SpecialPetrifyDrawPerFaceOffsetModel(BattleFxFreezeBreathDrawRecord *drawRecord, int reserved2, int reserved3, BattleFxPetrifyDrawPrim *reserved4, Vec3sPacked *faceOffsets, void *matrix, struct BattleFxOffsetTriMeshDesc *transVec)
{
    Vec3sPacked *cornerA;
    unsigned short tpage;
    int srcModelBase, faceTotal;
    BattleFxPetrifyDrawPrim *currPrimB;
    int capData;
    BattleFxPsxTexturedQuad *walkOfs;
    int faceIdx;
    int x;
    int matrixOut;
    int bytes;
    Vec3sPacked *ptB;
    int a;
    Vec3sPacked *pVertC;
    int d, e;
    short brightness;
    BattleFxFaceOffsets *pFaceBuf;
    BattleFxPetrifyDrawPrim *packetOut;

    pFaceBuf = (BattleFxFaceOffsets *)Gfx_GetPsxScratchpadPtr(0xC0);
    matrixOut = (int)pFaceBuf + 0x28;
    srcModelBase = drawRecord->modelData + 4;
    walkOfs = (BattleFxPsxTexturedQuad *)(srcModelBase + *(int *)drawRecord->modelData);
    packetOut = (BattleFxPetrifyDrawPrim *)Gfx_GetPsxPacketScratchPtr();
    faceTotal = walkOfs->flags;
    walkOfs = (BattleFxPsxTexturedQuad *)((char *)walkOfs + 2);
    tpage = walkOfs->flags & 0x19F | drawRecord->textureFlags;
    walkOfs = (BattleFxPsxTexturedQuad *)((char *)walkOfs + 2);
    cornerA = (Vec3sPacked *)(srcModelBase + walkOfs->flags);
    ptB = (Vec3sPacked *)(srcModelBase + walkOfs->vertex1);
    pVertC = (Vec3sPacked *)(srcModelBase + walkOfs->vertex2);
    for (faceIdx = 0; faceIdx < faceTotal; faceIdx++) {
        pFaceBuf->centroidX = (cornerA->vx + ptB->vx + pVertC->vx) / 3;
        pFaceBuf->centroidY = (cornerA->vy + ptB->vy + pVertC->vy) / 3;
        pFaceBuf->centroidZ = (cornerA->vz + ptB->vz + pVertC->vz) / 3;
        pFaceBuf->vertex0X = cornerA->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex0Y = cornerA->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex0Z = cornerA->vz - pFaceBuf->centroidZ;
        pFaceBuf->vertex1X = ptB->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex1Y = ptB->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex1Z = ptB->vz - pFaceBuf->centroidZ;
        pFaceBuf->vertex2X = pVertC->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex2Y = pVertC->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex2Z = pVertC->vz - pFaceBuf->centroidZ;
        transVec->transX = pFaceBuf->centroidX + faceOffsets->vx;
        transVec->transY = pFaceBuf->centroidY + faceOffsets->vy;
        transVec->transZ = pFaceBuf->centroidZ + faceOffsets->vz;
        faceOffsets = (Vec3sPacked *)((char *)faceOffsets + 8);
        MultiplyMatrix(matrix, transVec, (void *)matrixOut);
        SetRotMatrix((void *)matrixOut);
        SetTransMatrix((void *)matrixOut);
        RefreshGlobalTransformState();
        StoreDeferredDrawArgs(&pFaceBuf->vertex0X, &pFaceBuf->vertex1X, &pFaceBuf->vertex2X);
        ApplyDeferredDrawArgs();
        cornerA = (Vec3sPacked *)(srcModelBase + walkOfs->offsetC);
        ptB = (Vec3sPacked *)(srcModelBase + walkOfs->offsetD);
        pVertC = (Vec3sPacked *)(srcModelBase + walkOfs[1].flags);
        Gfx_PsxStoreClearFlag(&capData);
        if ((capData & 0x60000) == 0) {
            packetOut->tag = 0x7000000;
            Gfx_ReadTransformOrderingDepth2(&bytes);
            packetOut->colorWord = walkOfs->colorWord;
            packetOut->uvWord0 = walkOfs->uvWord0;
            packetOut->uvWord1 = walkOfs->uvWord1;
            packetOut->tpageWord = tpage;
            if ((drawRecord->drawFlags & 0x80) != 0) {
                brightness = walkOfs->vertex3 & 0xFF;
                packetOut->colorCommand = brightness << 0x10 | 0x24000000 | brightness << 8 | brightness;
            } else {
                brightness = drawRecord->shade;
                packetOut->colorCommand = brightness << 0x10 | 0x24000000 | brightness << 8 | brightness;
            }
            packetOut->polyCommand |= (char)((drawRecord->drawFlags & 8) != 0 ? 2 : 0);
            Gfx_DrawPsxPrimitive(packetOut);
        }
        walkOfs = (BattleFxPsxTexturedQuad *)((char *)walkOfs + 0x10);
    }
    walkOfs = (BattleFxPsxTexturedQuad *)((char *)walkOfs + 4);
    faceTotal = walkOfs->flags;
    walkOfs = (BattleFxPsxTexturedQuad *)((char *)walkOfs + 4);
    currPrimB = (BattleFxPetrifyDrawPrim *)packetOut;
    cornerA = (Vec3sPacked *)(srcModelBase + walkOfs->flags);
    ptB = (Vec3sPacked *)(srcModelBase + walkOfs->vertex1);
    pVertC = (Vec3sPacked *)(srcModelBase + walkOfs->vertex2);
    for (faceIdx = 0; faceIdx < faceTotal; faceIdx++) {
        pFaceBuf->centroidX = (cornerA->vx + ptB->vx + pVertC->vx) / 3;
        pFaceBuf->centroidY = (cornerA->vy + ptB->vy + pVertC->vy) / 3;
        pFaceBuf->centroidZ = (cornerA->vz + ptB->vz + pVertC->vz) / 3;
        pFaceBuf->vertex0X = cornerA->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex0Y = cornerA->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex0Z = cornerA->vz - pFaceBuf->centroidZ;
        pFaceBuf->vertex1X = ptB->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex1Y = ptB->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex1Z = ptB->vz - pFaceBuf->centroidZ;
        pFaceBuf->vertex2X = pVertC->vx - pFaceBuf->centroidX;
        pFaceBuf->vertex2Y = pVertC->vy - pFaceBuf->centroidY;
        pFaceBuf->vertex2Z = pVertC->vz - pFaceBuf->centroidZ;
        transVec->transX = pFaceBuf->centroidX + faceOffsets->vx;
        transVec->transY = pFaceBuf->centroidY + faceOffsets->vy;
        transVec->transZ = pFaceBuf->centroidZ + faceOffsets->vz;
        faceOffsets = (Vec3sPacked *)((char *)faceOffsets + 8);
        MultiplyMatrix(matrix, transVec, (void *)matrixOut);
        SetRotMatrix((void *)matrixOut);
        SetTransMatrix((void *)matrixOut);
        RefreshGlobalTransformState();
        StoreDeferredDrawArgs(&pFaceBuf->vertex0X, &pFaceBuf->vertex1X, &pFaceBuf->vertex2X);
        ApplyDeferredDrawArgs();
        cornerA = (Vec3sPacked *)(srcModelBase + walkOfs[1].flags);
        ptB = (Vec3sPacked *)(srcModelBase + walkOfs[1].vertex1);
        pVertC = (Vec3sPacked *)(srcModelBase + walkOfs[1].vertex2);
        Gfx_PsxStoreClearFlag(&capData);
        if ((capData & 0x60000) == 0) {
            currPrimB->tag = 0x6000000;
            Gfx_ReadTransformOrderingDepth2(&bytes);
            Gfx_ShadePsxTriVertexColors((CVECTOR *)((char *)walkOfs + 8), (CVECTOR *)((char *)walkOfs + 0xC), (CVECTOR *)((char *)walkOfs + 0x10), drawRecord->shade, (CVECTOR *)((int)currPrimB + 4), (CVECTOR *)((int)currPrimB + 0xC), (CVECTOR *)((int)currPrimB + 0x14));
            currPrimB->polyCommand = ((drawRecord->drawFlags & 8) != 0 ? 2 : 0) + 0x30;
            Gfx_DrawPsxPrimitive(currPrimB);
        }
        walkOfs++;
    }
    return (int)currPrimB;
}

/*
 * Per-frame tick of one falling sprite: installs the billboard matrix at its position with scale
 * 0x3000 and chains its draw onto g_BattleSpecPetrifyDrawListHead. While the battle is not paused it
 * adds the velocity to the position, adds 0x14 to the y velocity (gravity) and advances the frame,
 * retiring the sprite when the frame reaches the sprite group's frame count.
 */
// FUNCTION: FF7 0x0051daca
void __cdecl BattleFx_SpecialPetrifyFallingSpriteTask(void)
{
    BattleFxPulseOfLifeSprite *task;

    task = (BattleFxPulseOfLifeSprite *)BATTLE_CURRENT_TASK_SLOT;
    g_BattleSpecPetrifySpriteRequest2.sprite[1].spriteGroup = (BattleFxSpriteGroup *)Gfx_ModelTableGetLoadedRecord(0x10, g_BattleSpecPetrifyLoadedResTable);
    g_BattleSpecPetrifySpriteRequest2.sprite[1].drawObj = Battle3d_GetSceneRenderObject(1, g_pBattle3dScene);
    BattleFx_InstallBillboardMatrix(&task->posX, 0x3000, 0);
    g_BattleSpecPetrifySpriteRequest2.sprite[1].frame = task->frame;
    g_BattleSpecPetrifyDrawListHead = BattleFx_SubmitSpriteDraw(&g_BattleSpecPetrifySpriteRequest2.sprite[1], g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleSpecPetrifyDrawListHead);
    if (g_BattleIsPaused == 0) {
        task->posX += task->velocityX;
        task->posY += task->velocityY;
        task->posZ += task->velocityZ;
        task->velocityY += 0x14;
        if (g_BattleSpecPetrifySpriteRequest2.sprite[1].spriteGroup != 0) {
            (task->frame)++;
            if (task->frame == ((BattlePetrifySpriteGroup *)g_BattleSpecPetrifySpriteRequest2.sprite[1].spriteGroup)->header->frameCount) {
                task->ownerSlot = BATTLE_TASK_FREE;
            }
        }
    }
}

/*
 * Adds the 128 velocity triples to their position triples, increases each y velocity by 20, and
 * whenever the new y position is positive clamps it to zero and negates the y velocity.
 */
// FUNCTION: FF7 0x0051dbf0
void __cdecl BattleFx_SpecialPetrifyUpdateBouncingParticles(void)
{
    short i;

    for (i = 0; i < 0x80; i++) {
        g_BattleSpecPetrifyBuffer2[i].x += g_BattleSpecPetrifyBuffer1[i].x;
        g_BattleSpecPetrifyBuffer2[i].y += g_BattleSpecPetrifyBuffer1[i].y;
        g_BattleSpecPetrifyBuffer2[i].z += g_BattleSpecPetrifyBuffer1[i].z;
        g_BattleSpecPetrifyBuffer1[i].y += 0x14;
        if (g_BattleSpecPetrifyBuffer2[i].y > 0) {
            g_BattleSpecPetrifyBuffer2[i].y = 0;
            g_BattleSpecPetrifyBuffer1[i].y = -g_BattleSpecPetrifyBuffer1[i].y;
        }
    }
}

/*
 * One arm of the spiral: draws the spiral model along the path with a sine-driven twist and, on
 * even arms, spawns a two-phase sprite at the arm's far end. It retires after 0x20 frames.
 */
// FUNCTION: FF7 0x0051dce1
void __cdecl BattleFx_SpecialPetrifySpiralModelTask(void)
{
#pragma pack(push, 1)
    /* Locals by stack slot: see FRAME UNION in lib/codegen.h. */
    union {
        unsigned char storage[132];
        int spriteParam;
        struct { unsigned char pad_to_4[0x4]; SVECTOR angleX; };
        struct { unsigned char pad_to_C[0xC]; SVECTOR pointX; };
        struct { unsigned char pad_to_14[0x14]; PsxMatrix spiralMatrix; };
        struct { unsigned char pad_to_34[0x34]; BattleFxPetrifyTwoPhaseSpriteSlot *twoPhaseSlot; };
        struct { unsigned char pad_to_40[0x40]; int rotatedPoint; };
        struct { unsigned char pad_to_44[0x44]; SVECTOR baseAngleX; };
        struct { unsigned char pad_to_4C[0x4C]; BattleFxPetrifySpiralModelSlot *spiralSlot; };
        struct { unsigned char pad_to_70[0x70]; short armSign; };
        struct { unsigned char pad_to_74[0x74]; VECTOR scaleVector; };
    } frame;
#pragma pack(pop)

    frame.spiralSlot = (BattleFxPetrifySpiralModelSlot *)BATTLE_CURRENT_TASK_SLOT;
    frame.armSign = (frame.spiralSlot->spiralArm >> 1) * 2 - 1;
    frame.angleX.vx = SinFixed(frame.spiralSlot->frameCounter << 8) / 0x28 * frame.armSign;
    frame.baseAngleX.vx = frame.angleX.vx;
    frame.angleX.vy = (SinFixed(frame.spiralSlot->frameCounter << 7) >> 5) * frame.armSign;
    frame.baseAngleX.vy = frame.angleX.vy;
    frame.angleX.vz = 0;
    frame.baseAngleX.vz = frame.angleX.vz;
    frame.angleX.vx -= 0x400;
    RotMatrix(&frame.angleX, &frame.spiralMatrix);
    ConcatMatrixPreservingTranslation(&g_BattleSpecPetrifyLookBasis, &frame.spiralMatrix, &frame.spiralMatrix);
    frame.scaleVector.vy = frame.spiralSlot->scaledPathLength;
    frame.scaleVector.vz = 0x3000;
    frame.scaleVector.vx = frame.scaleVector.vz;
    ScaleMatrix(&frame.spiralMatrix, &frame.scaleVector);
    frame.spiralMatrix.t[0] = frame.spiralSlot->offsetX;
    frame.spiralMatrix.t[1] = frame.spiralSlot->offsetY;
    frame.spiralMatrix.t[2] = frame.spiralSlot->offsetZ;
    MultiplyMatrix(&g_BattleCameraTransform, &frame.spiralMatrix, &frame.spiralMatrix);
    SetRotMatrix(&frame.spiralMatrix);
    SetTransMatrix(&frame.spiralMatrix);
    SetDrawColorRGB(0, 0, 0);
    if ((frame.spiralSlot->spiralArm % 2) == 0) {
        (g_BattleSpecPetrifySpriteRequest4.model) = Gfx_ModelTableGetRenderObject(1, g_BattleSpecPetrifyLoadedResTable);
    } else {
        (g_BattleSpecPetrifySpriteRequest4.model) = Gfx_ModelTableGetRenderObject(0, g_BattleSpecPetrifyLoadedResTable);
    }
    if ((frame.spiralSlot->spiralArm % 2) == 0) {
        frame.spriteParam = 0x1000 - (g_BattleSpecPetrifyActiveCount << 5);
    } else {
        frame.spriteParam = 0x1000 - g_BattleSpecPetrifyActiveCount * 0x18;
    }
    g_BattleSpecPetrifySpriteRequest4.req4Word10 = *(short *)&frame.spriteParam;
    g_BattleSpecPetrifyDrawListHead = BattleFx_SubmitModelDraw((BattleFxModelDraw *)&g_BattleSpecPetrifySpriteRequest4, g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleSpecPetrifyDrawListHead);
    if (g_BattleIsPaused != 0) {
        return;
    }
    if ((frame.spiralSlot->spiralArm % 2) == 0) {
        frame.twoPhaseSlot = (BattleFxPetrifyTwoPhaseSpriteSlot *)BATTLE_NEW_TASK_SLOT(BattleFx_SpecialPetrifyTwoPhaseSpriteTask);
        frame.twoPhaseSlot->offsetX = frame.spiralSlot->offsetX;
        frame.twoPhaseSlot->offsetY = frame.spiralSlot->offsetY;
        frame.twoPhaseSlot->offsetZ = frame.spiralSlot->offsetZ;
        frame.pointX.vx = 0;
        frame.pointX.vy = 0;
        frame.pointX.vz = frame.spiralSlot->pathLength;
        RotMatrix(&frame.baseAngleX, &frame.spiralMatrix);
        ConcatMatrixPreservingTranslation(&g_BattleSpecPetrifyLookBasis, &frame.spiralMatrix, &frame.spiralMatrix);
        frame.spiralMatrix.t[0] = frame.twoPhaseSlot->offsetX;
        frame.spiralMatrix.t[1] = frame.twoPhaseSlot->offsetY;
        frame.spiralMatrix.t[2] = frame.twoPhaseSlot->offsetZ;
        SetRotMatrix(&frame.spiralMatrix);
        SetTransMatrix(&frame.spiralMatrix);
        RotTransPointToInt16(&frame.pointX, &frame.twoPhaseSlot->offsetX, &frame.rotatedPoint);
        frame.twoPhaseSlot->clearedWordA = 0;
        frame.twoPhaseSlot->headingAngleY = frame.spiralSlot->headingAngleY;
        frame.twoPhaseSlot->clearedWordB = 0;
        frame.twoPhaseSlot->phase = 0;
    }
    if (frame.spiralSlot->frameCounter < 8) {
        g_BattleSpecPetrifyActiveCount++;
    }
    if (frame.spiralSlot->frameCounter > 0x18) {
        g_BattleSpecPetrifyActiveCount--;
    }
    (frame.spiralSlot->frameCounter)++;
    if (frame.spiralSlot->frameCounter == 0x20) {
        frame.spiralSlot->ownerSlot = BATTLE_TASK_FREE;
    }
}

/*
 * Per-frame tick of one two-phase sprite: installs the billboard matrix at its position with scale
 * 0x2400, loads the sprite of animation 0xB in phase 0 or 0xC in phase 1, and chains its draw onto
 * g_BattleSpecPetrifyDrawListHead. While the battle is not paused it advances the frame; at the
 * sprite group's frame count it switches to phase 1 and restarts, or retires after phase 1.
 */
// FUNCTION: FF7 0x0051e068
void __cdecl BattleFx_SpecialPetrifyTwoPhaseSpriteTask(void)
{
    BattleFxPetrifyTwoPhaseSpriteSlot *task;

    task = (BattleFxPetrifyTwoPhaseSpriteSlot *)BATTLE_CURRENT_TASK_SLOT;
    BattleFx_InstallBillboardMatrix(&task->offsetX, 0x2400, 0);
    if (task->phase == 0) {
        g_BattleSpecPetrifySpriteRequest1.sprite[0].spriteGroup = (BattleFxSpriteGroup *)Gfx_ModelTableGetLoadedRecord(0xB, g_BattleSpecPetrifyLoadedResTable);
        g_BattleSpecPetrifySpriteRequest1.sprite[0].drawObj = Gfx_ModelTableGetSpriteObject(0xB, g_BattleSpecPetrifyLoadedResTable);
    } else {
        g_BattleSpecPetrifySpriteRequest1.sprite[0].spriteGroup = (BattleFxSpriteGroup *)Gfx_ModelTableGetLoadedRecord(0xC, g_BattleSpecPetrifyLoadedResTable);
        g_BattleSpecPetrifySpriteRequest1.sprite[0].drawObj = Gfx_ModelTableGetSpriteObject(0xC, g_BattleSpecPetrifyLoadedResTable);
    }
    g_BattleSpecPetrifySpriteRequest1.sprite[0].frame = task->frameCounter;
    g_BattleSpecPetrifyDrawListHead = BattleFx_SubmitSpriteDraw(&g_BattleSpecPetrifySpriteRequest1.sprite[0], g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleSpecPetrifyDrawListHead);
    if (g_BattleIsPaused == 0 && g_BattleSpecPetrifySpriteRequest1.sprite[0].spriteGroup != 0) {
        (task->frameCounter)++;
        if (task->frameCounter >= ((BattlePetrifySpriteGroup *)g_BattleSpecPetrifySpriteRequest1.sprite[0].spriteGroup)->header->frameCount) {
            if (task->phase == 0) {
                task->phase = 1;
                task->frameCounter = 0;
            } else {
                task->ownerSlot = BATTLE_TASK_FREE;
            }
        }
    }
}
