/*
 * Queues BattleFx_SpecialSpawnPetrifyPerTarget for each actor in actorMask (interval 4),
 * clears the timeline's color channels, starts a fixed-point ramp to 0x1000 over ten frames, plays
 * the opening sound panned to sourceIndex and seeds the particle velocities.
 */
// FUNCTION: FF7 0x0051c4c3
void __cdecl BattleFx_SpecialBeginPetrify(int targetMask, int actorIdx)
{
    int p, q, r;

    Battle_CreateBitPatternCallbackTask(targetMask, actorIdx, 4, BattleFx_SpecialSpawnPetrifyPerTarget);
    g_BattleFxTimelineState.channel2 = 0;
    g_BattleFxTimelineState.channel1 = g_BattleFxTimelineState.channel2;
    g_BattleFxTimelineState.red = g_BattleFxTimelineState.channel1;
    Battle_StartFixedPointRamp(0x1000, 0xA);
    Battle_PlaySfxPannedToActor(0x62, (short)actorIdx, 0x40);
    BattleFx_SpecialPetrifyInitParticleVelocities();
}

/*
 * Resets the 128 bouncing particles: each starts at the origin with a random launch velocity, x and
 * z from a random angle and a radius below 180, and y a random upward speed of 100 to 199.
 */
// FUNCTION: FF7 0x0051c526
void __cdecl BattleFx_SpecialPetrifyInitParticleVelocities(void)
{
    short i, rad, angle;

    for (i = 0; i < 0x80; i++) {
        rad = rand() % 0xB4;
        angle = rand() % 0x1000;
        g_BattleSpecPetrifyBuffer2[i].z = 0;
        g_BattleSpecPetrifyBuffer2[i].y = 0;
        g_BattleSpecPetrifyBuffer2[i].x = 0;
        g_BattleSpecPetrifyBuffer1[i].x = CosFixed(angle) * rad >> 0xC;
        g_BattleSpecPetrifyBuffer1[i].z = SinFixed(angle) * rad >> 0xC;
        g_BattleSpecPetrifyBuffer1[i].y = -rand() % 0x64 - 0x64;
    }
}

// Allocates a BattleFx_SpecialPetrifyTimelineTask slot and fills it: the start point is the world
// position of the target's bone34 and the end point the world position of the actor's targetBone
// (both via Battle_GetBoneWorldPos), and the actor is stored in the slot. The direction from start
// to end goes to Gte_BuildLookBasisFromDirection, which fills g_BattleSpecPetrifyLookBasis. It then
// plays sound 0x62 panned to the target.
// FUNCTION: FF7 0x0051c60f
void __cdecl BattleFx_SpecialSpawnPetrifyPerTarget(int actor, int targetIndex)
{
    short direction[3];
    BattleFxPetrifyTimeline *timeline;

    timeline = (BattleFxPetrifyTimeline *)BATTLE_NEW_TASK_SLOT(BattleFx_SpecialPetrifyTimelineTask);
    Battle_GetBoneWorldPos(targetIndex, g_BattleActorRecords[targetIndex].bone34, &timeline->startX);
    Battle_GetBoneWorldPos(actor, g_BattleActorRecords[actor].targetBone, &timeline->endX);
    timeline->actorIndex = actor;
    direction[0] = timeline->endX - timeline->startX;
    direction[1] = timeline->endY - timeline->startY;
    direction[2] = timeline->endZ - timeline->startZ;
    Gte_BuildLookBasisFromDirection(direction, (short *)&g_BattleSpecPetrifyLookBasis);
    Battle_PlaySfxPannedToActor(0x62, targetIndex, 0);
}

