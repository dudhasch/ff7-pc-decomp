// Returns while paused. At zero loads sounds 0x30,0x15A,0xFA into slot zero; at fifty-four
// dispatches 0x30 with saved attacker. For retained sequence below six, matching timing table entry
// schedules BattleFx_LimitDragonDiveImpactTask with attacker/target/sequence. Reads target XYZ, derives
// XZ angle from target minus saved origin plus 0x800 and stores it; offsets target X/Z by
// sine/cosine times actor radius short plus 3500, sets task Y zero and advances sequence.
// Increments count and exactly 240 restores attacker XYZ and Y angle from saved task fields,
// retires and releases all three sounds slot fifteen.
// FUNCTION: FF7 0x004af424
void __cdecl BattleFx_LimitDragonDiveTimelineTask(void)
{
#pragma pack(push, 1)
    /* Locals by stack slot: see FRAME UNION in lib/codegen.h. */
    union {
        unsigned char storage[32];
        short targetActor;
        struct { unsigned char pad_to_4[0x4]; short targetX; };
        struct { unsigned char pad_to_6[0x6]; short targetY; };
        struct { unsigned char pad_to_8[0x8]; short targetZ; };
        struct { unsigned char pad_to_C[0xC]; BattleFxLimitDragonDiveImpactSlot *impactSlot; };
        struct { unsigned char pad_to_14[0x14]; short radius; };
        struct { unsigned char pad_to_18[0x18]; BattleLimitDragonDiveTimeline *timeline; };
        struct { unsigned char pad_to_1C[0x1C]; short angle; };
    } frame;
#pragma pack(pop)

    frame.timeline = (BattleLimitDragonDiveTimeline *)BATTLE_CURRENT_TASK_SLOT;
    if (g_BattleIsPaused != 0) {
        return;
    }
    if (frame.timeline->frame == 0) {
        SfxLoadIntoBuffer(0x30, 0);
        SfxLoadIntoBuffer(0x15A, 0);
        SfxLoadIntoBuffer(0xFA, 0);
    }
    if (frame.timeline->frame == 54) {
        Battle_PlaySfxPannedToActor(0x30, (short)frame.timeline->slotIndex, 0);
    }
    if (g_BattleLimitDragonDiveImpactIndex < 6 && frame.timeline->frame == (&g_BattleLimitDragonDiveModelDrawRequest.impactFrames)[g_BattleLimitDragonDiveImpactIndex]) {
        frame.impactSlot = (BattleFxLimitDragonDiveImpactSlot *)BATTLE_NEW_TASK_SLOT(BattleFx_LimitDragonDiveImpactTask);
        frame.impactSlot->slotIndex = frame.timeline->slotIndex;
        frame.targetActor = g_BattleHitTargetActors[g_BattleLimitDragonDiveImpactIndex];
        frame.impactSlot->targetActorIndex = frame.targetActor;
        frame.impactSlot->impactIndex = g_BattleLimitDragonDiveImpactIndex;
        frame.targetX = g_BattleActorRecords[frame.targetActor].posX;
        frame.targetY = g_BattleActorRecords[frame.targetActor].posY;
        frame.targetZ = g_BattleActorRecords[frame.targetActor].posZ;
        frame.angle = ArcTangentFixed(frame.targetX - frame.timeline->posA, frame.targetZ - frame.timeline->posC) + 0x800;
        frame.impactSlot->yaw = frame.angle;
        frame.radius = g_BattleActorRecords[frame.targetActor].radius + 3500;
        frame.targetX += (short)(SinFixed(frame.angle) * frame.radius >> 12);
        frame.impactSlot->posX = frame.targetX;
        frame.impactSlot->posY = 0;
        frame.targetZ += (short)(CosFixed(frame.angle) * frame.radius >> 12);
        frame.impactSlot->posZ = frame.targetZ;
        g_BattleLimitDragonDiveImpactIndex++;
    }
    (frame.timeline->frame)++;
    if (frame.timeline->frame == 240) {
        g_BattleActorRecords[frame.timeline->slotIndex].posX = frame.timeline->posA;
        g_BattleActorRecords[frame.timeline->slotIndex].posY = frame.timeline->posB;
        g_BattleActorRecords[frame.timeline->slotIndex].posZ = frame.timeline->posC;
        g_BattleActorRecords[frame.timeline->slotIndex].yaw = frame.timeline->savedYaw;
        frame.timeline->endFlag = 0xFFFF;
        Sfx_ReleaseCachedBuffer(0x30, 0xF);
        Sfx_ReleaseCachedBuffer(0x15A, 0xF);
        Sfx_ReleaseCachedBuffer(0xFA, 0xF);
    }
}

// Returns while paused. At ten allocates ring record type ten with saved target/sequence, sets task
// field 0xE to signed -210, calls BattleFx_HitMarkSpawnScriptAtActorBone(target,0x23,4096) and
// dispatches 0x15A with attacker. At fifteen schedules BattleFx_LimitDragonDiveScalingModelTask at
// target XYZ with three 2000 shorts in fields 0xC..0x10, schedules
// BattleFx_LimitDragonDiveScreenFlashTask without local initialization and dispatches 0xFA with
// attacker. Increments count and exactly twenty-eight retires, then still copies saved XYZ and Y
// angle into attacker state.
// FUNCTION: FF7 0x004af6f4
void __cdecl BattleFx_LimitDragonDiveImpactTask(void)
{
    BattleFxDragonDiveImpact *ring;
    BattleFxLimitDragonDiveRecord *taskPtr;
    BattleFxSpecialEnergyOrbSlot *child;

    taskPtr = (BattleFxLimitDragonDiveRecord *)BATTLE_CURRENT_TASK_SLOT;
    if (g_BattleIsPaused != 0) {
        return;
    }
    if (taskPtr->phase == 0xA) {
        ring = (BattleFxDragonDiveImpact *)Battle_AllocSceneMessage(0xA);
        ring->targetActorIndex = taskPtr->targetActorIndex;
        ring->impactIndex = taskPtr->impactIndex;
        taskPtr->unusedWord = 0xFF2E;
        BattleFx_HitMarkSpawnScriptAtActorBone(taskPtr->targetActorIndex, 0x23, 0x1000 /* 1.0 */);
        Battle_PlaySfxPannedToActor(0x15A, (short)taskPtr->actorIndex, 0);
    }
    if (taskPtr->phase == 0xF) {
        child = (BattleFxSpecialEnergyOrbSlot *)BATTLE_NEW_TASK_SLOT(BattleFx_LimitDragonDiveScalingModelTask);
        child->posX = g_BattleActorRecords[taskPtr->targetActorIndex].posX;
        child->posY = g_BattleActorRecords[taskPtr->targetActorIndex].posY;
        child->posZ = g_BattleActorRecords[taskPtr->targetActorIndex].posZ;
        child->velocityX = 2000;
        child->velocityY = 2000;
        child->velocityZ = 2000;
        child = (BattleFxSpecialEnergyOrbSlot *)BATTLE_NEW_TASK_SLOT(BattleFx_LimitDragonDiveScreenFlashTask);
        Battle_PlaySfxPannedToActor(0xFA, (short)taskPtr->actorIndex, 0);
    }
    (taskPtr->phase)++;
    if (taskPtr->phase == 0x1C) {
        taskPtr->ownerSlot = BATTLE_TASK_FREE;
    }
    g_BattleActorRecords[taskPtr->actorIndex].posX = taskPtr->posX;
    g_BattleActorRecords[taskPtr->actorIndex].posY = taskPtr->posY;
    g_BattleActorRecords[taskPtr->actorIndex].posZ = taskPtr->posZ;
    g_BattleActorRecords[taskPtr->actorIndex].yaw = taskPtr->yaw;
}

// Per-frame screen flash: calls BattleFx_FlashScreenWhite(g_BattleLimitDragonDiveFlashRed, 0,
// g_BattleLimitDragonDiveFlashIntensity) and stores the result in g_BattleOverlayDrawListHead. Unless
// g_BattleIsPaused is set, it ramps both values up by 0x18 for frames 0-4, ramps the red down for
// frames 5-9, ramps the intensity down from frame 10, and frees the slot on frame 15.
// FUNCTION: FF7 0x004af8e8
void __cdecl BattleFx_LimitDragonDiveScreenFlashTask(void)
{
    BattleTaskSlot *task;

    task = BATTLE_CURRENT_TASK_SLOT;
    g_BattleOverlayDrawListHead = (int)BattleFx_FlashScreenWhite((unsigned char)g_BattleLimitDragonDiveFlashRed, 0, (unsigned char)g_BattleLimitDragonDiveFlashIntensity);
    if (g_BattleIsPaused != 0) {
        return;
    }
    if (task->frameCounter < 5) {
        g_BattleLimitDragonDiveFlashRed += 0x18;
        g_BattleLimitDragonDiveFlashIntensity += 0x18;
    }
    if (task->frameCounter >= 5 && task->frameCounter < 10) {
        g_BattleLimitDragonDiveFlashRed -= 0x18;
    }
    if (task->frameCounter >= 10) {
        g_BattleLimitDragonDiveFlashIntensity -= 0x18;
    }
    (task->frameCounter)++;
    if (task->frameCounter == 15) {
        task->ownerSlot = BATTLE_TASK_FREE;
    }
}

// Refreshes D_Dive resource field zero, builds retained rotation and scale from three task shorts,
// sets saved X/Z translation with Y zero and composes g_BattleCameraTransform. Installs matrix, sets black
// draw colour and submits model at destination plus 0x70 shift twelve, chaining g_BattleLimitDragonDiveModelDrawHandle.
// After paused return, first five counts set retained callback value count plus one and iterate
// polygon parts through BattleFx_LimitDragonDiveBlendPolygonSetVertices when resource nonzero; next five increase Y scale by 400.
// From ten onward subtract 400 from X/Z scales and add 200 to Y scale. Earlier counts instead emit
// one BattleFx_LimitDragonDiveVerticalMovingSpriteTask per call at radius 1500 around saved X/Z, random
// negative Y remainder 1000 and Y velocity -400. Increments count and exactly fifteen retires.
// FUNCTION: FF7 0x004af9c7
void __cdecl BattleFx_LimitDragonDiveScalingModelTask(void)
{
#pragma pack(push, 1)
    /* Locals by stack slot: see FRAME UNION in lib/codegen.h. */
    union {
        unsigned char storage[132];
        struct { unsigned char pad_to_8[0x8]; PsxMatrix rotMatrix; };
        struct { unsigned char pad_to_28[0x28]; BattleFxDragonDiveSpriteRecord *spriteRecord; };
        struct { unsigned char pad_to_30[0x30]; short angle; };
        struct { unsigned char pad_to_34[0x34]; BattleFxLimitDragonDiveScaling *scalingSlot; };
        struct { unsigned char pad_to_38[0x38]; PsxMatrix composedMatrix; };
        struct { unsigned char pad_to_6C[0x6C]; VECTOR scaleX; };
    } frame;
#pragma pack(pop)

    frame.scalingSlot = (BattleFxLimitDragonDiveScaling *)BATTLE_CURRENT_TASK_SLOT;
    (g_BattleLimitDragonDiveModelDrawRequest.resource) = Gfx_ModelTableGetRenderObject(0, g_BattleLimitDragonDiveLoadedResTable);
    RotMatrix((SVECTOR *)&g_BattleLimitDragonDiveRotationMatrix, &frame.rotMatrix);
    frame.scaleX.vx = frame.scalingSlot->scaleX;
    frame.scaleX.vy = frame.scalingSlot->scaleY;
    frame.scaleX.vz = frame.scalingSlot->scaleZ;
    ScaleMatrix(&frame.rotMatrix, &frame.scaleX);
    frame.rotMatrix.t[0] = frame.scalingSlot->posX;
    frame.rotMatrix.t[1] = 0;
    frame.rotMatrix.t[2] = frame.scalingSlot->posZ;
    MultiplyMatrix(&g_BattleCameraTransform, &frame.rotMatrix, &frame.composedMatrix);
    SetRotMatrix(&frame.composedMatrix);
    SetTransMatrix(&frame.composedMatrix);
    SetDrawColorRGB(0, 0, 0);
    g_BattleLimitDragonDiveModelDrawHandle = BattleFx_SubmitModelDraw((BattleFxModelDraw *)&g_BattleLimitDragonDiveModelDrawRequest, g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleLimitDragonDiveModelDrawHandle);
    if (g_BattleIsPaused != 0) {
        return;
    }
    if (frame.scalingSlot->frameCount < 10) {
        if (frame.scalingSlot->frameCount < 5) {
            g_BattleLimitDragonDiveImpactFrame = frame.scalingSlot->frameCount + 1;
            if ((g_BattleLimitDragonDiveModelDrawRequest.resource) != 0) {
                Gfx_ForEachPolygonSetPart((DxGroupPartCallback)BattleFx_LimitDragonDiveBlendPolygonSetVertices, *(int *)((char *)(g_BattleLimitDragonDiveModelDrawRequest.resource) + 4));
            }
        } else {
            frame.scalingSlot->scaleY += 0x190;
        }
    }
    if (frame.scalingSlot->frameCount >= 10) {
        frame.scalingSlot->scaleX -= 0x190;
        frame.scalingSlot->scaleZ -= 0x190;
        frame.scalingSlot->scaleY += 0xC8;
    } else {
        frame.spriteRecord = (BattleFxDragonDiveSpriteRecord *)BATTLE_NEW_TASK_SLOT(BattleFx_LimitDragonDiveVerticalMovingSpriteTask);
        frame.angle = (rand() % 4096);
        frame.spriteRecord->posX = frame.scalingSlot->posX + (SinFixed(frame.angle) * 0x5DC >> 12);
        frame.spriteRecord->posZ = frame.scalingSlot->posZ + (CosFixed(frame.angle) * 0x5DC >> 12);
        frame.spriteRecord->posY = -rand() % 1000;
        frame.spriteRecord->velocityY = 0xFE70;
    }
    (frame.scalingSlot->frameCount)++;
    if (frame.scalingSlot->frameCount == 15) {
        frame.scalingSlot->ownerSlot = BATTLE_TASK_FREE;
    }
}

// One frame of a vertically moving billboard sprite: the texture comes from entry 1 of
// g_BattleLimitDragonDiveLoadedResTable but the clut from Battle3d_GetSceneRenderObject(1, g_pBattle3dScene).
// It installs the billboard at scale 0x4000 and submits the sprite request threading
// g_BattleOverlayDrawListHead. While g_BattleIsPaused is clear the sprite moves along Y by its
// velocity, and with a nonnull request the frame advances and the slot is freed when the frame
// equals the animation length.
// FUNCTION: FF7 0x004afc2f
void __cdecl BattleFx_LimitDragonDiveVerticalMovingSpriteTask(void)
{
    BattleFxDragonDiveVerticalSprite *task;

    task = (BattleFxDragonDiveVerticalSprite *)BATTLE_CURRENT_TASK_SLOT;
    (g_BattleLimitDragonDiveSpriteRequest.handle) = Gfx_ModelTableGetLoadedRecord(1, g_BattleLimitDragonDiveLoadedResTable);
    g_BattleLimitDragonDiveSpriteRequest.res = Battle3d_GetSceneRenderObject(1, g_pBattle3dScene);
    BattleFx_InstallBillboardMatrix(&task->posX, 0x4000 /* 4.0 */, 0);
    g_BattleLimitDragonDiveSpriteRequest.frame = task->frame;
    g_BattleOverlayDrawListHead = BattleFx_SubmitSpriteDraw(&g_BattleLimitDragonDiveSpriteRequest, g_BattleCurrentOrderingTable + BATTLE_OT_DEPTH_SORTED, 0xC, g_BattleOverlayDrawListHead);
    if (g_BattleIsPaused == 0) {
        task->posY += task->velocityY;
        if ((g_BattleLimitDragonDiveSpriteRequest.handle) != 0) {
            (task->frame)++;
            if (task->frame == *(int *)((char *)*(int *)(g_BattleLimitDragonDiveSpriteRequest.handle) + 4)) {
                task->ownerSlot = BATTLE_TASK_FREE;
            }
        }
    }
}
