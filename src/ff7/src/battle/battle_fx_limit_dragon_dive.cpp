// When scene pointer is nonzero and g_BattleLimitDragonDiveLoadedResTable is zero, initializes local
// resource record with default duration, clears first field and builds LIMIT3/D_DIVE path into
// field eight. Calls Gfx_LoadModelTableIfAbsent with type two, descriptor
// g_BattleLimitDragonDiveResourceDef, local record, cache g_BattleLimitDragonDiveLoadedResTable and scene
// field 0x4C. Otherwise does nothing. Helpers determine allocation/failure behavior.
// FUNCTION: FF7 0x004af1e0
void __cdecl BattleFx_LimitLoadResDragonDive(void)
{
    GfxModelTableBank *ownerHandle;
    GfxResourceRequest recordBuf;
    int kind;
    char pathText[200];
    GfxResourceRequest *pRequest;
    int stepResourceDef;

    if (g_pBattle3dScene != 0 && g_BattleLimitDragonDiveLoadedResTable == 0) {
        kind = 2;
        stepResourceDef = (int)&g_BattleLimitDragonDiveResourceDef;
        ownerHandle = (GfxModelTableBank *)(g_pBattle3dScene->modelTableBank);
        pRequest = &recordBuf;
        Gfx_InitResourceRequest(pRequest);
        pRequest->groupTag = 0;
        // STRING: FF7 0x00806e54
        pRequest->resourcePath = BattleFx_BuildResourcePath("LIMIT3/D_DIVE", pathText);
        Gfx_LoadModelTableIfAbsent(kind, stepResourceDef, pRequest, &g_BattleLimitDragonDiveLoadedResTable, ownerHandle);
    }
}

// Loads DDive resources, clears g_BattleLimitDragonDiveImpactIndex/28/20, visits model-field-0 polygon parts with
// BattleFx_LimitDragonDiveBlendPolygonSetVertices after clearing g_BattleLimitDragonDiveImpactFrame when the field exists, calls BattleFx_LimitBeginDragonDive, and returns
// zero.
// FUNCTION: FF7 0x004af270
int __cdecl BattleFx_LimitEnterDragonDive(int targetMask, int actorIdx)
{
    int val;

    BattleFx_LimitLoadResDragonDive();
    g_BattleLimitDragonDiveImpactIndex = 0;
    g_BattleLimitDragonDiveFlashRed = 0;
    g_BattleLimitDragonDiveFlashIntensity = 0;
    val = Gfx_ModelTableGetRenderObject(0, g_BattleLimitDragonDiveLoadedResTable);
    if (val != 0) {
        g_BattleLimitDragonDiveImpactFrame = 0;
        Gfx_ForEachPolygonSetPart((DxGroupPartCallback)BattleFx_LimitDragonDiveBlendPolygonSetVertices, *(int *)((char *)val + 4));
    }
    BattleFx_LimitBeginDragonDive(targetMask, actorIdx);
    return 0;
}

// Interpolates each of three signed-short coordinates from the stride-eight row at
// g_BattleLimitDragonDivePolygonVertexBlob (0x806648) toward the corresponding row at 0x806A18 by
// g_BattleLimitDragonDiveImpactFrame divided by 5.0, writing floats at dst offsets zero, four and eight.
// Does not use unusedArg or clamp the interpolation factor.
// FUNCTION: FF7 0x004af2e1
void __cdecl BattleFx_LimitDragonDiveBlendPolygonSetVertices(int index, int unusedArg, BattleFxHellBomberEndVertex *dst)
{
    Vec3sPacked *vert;
    int x0;
    float frac;
    Vec3sPacked *targetPointer;
    int offsetX;
    int originZ;
    int offsetY;
    int y0;
    int distZ;

    frac = g_BattleLimitDragonDiveImpactFrame / 5.0f;
    vert = (Vec3sPacked *)(index * 8 + (char *)&g_BattleLimitDragonDivePolygonVertexBlob);
    targetPointer = (Vec3sPacked *)(index * 8 + (char *)&g_BattleLimitDragonDivePolygonVertexBlob + 0x3d0);
    x0 = vert->vx;
    dst->posX = x0 + (offsetX = targetPointer->vx - vert->vx) * frac;
    y0 = vert->vy;
    dst->posY = y0 + (offsetY = targetPointer->vy - vert->vy) * frac;
    originZ = vert->vz;
    dst->posZ = originZ + (distZ = targetPointer->vz - vert->vz) * frac;
}

