// Rejects a null record or an index at least the unsigned-short animation count. Otherwise binds
// the indexed animation pointer, stores the narrowed index in animId and prevAnimId, copies the
// player's frameCount to record->animIndex, and returns 1.
// FUNCTION: FF7 0x0077a339
int __cdecl Mini_ChocoboSelectAnimationIndex(ChocoboRacerEntry *record, int animIndex)
{
    if (record == 0) {
        return 0;
    } else if (animIndex >= record->animCount) {
        return 0;
    } else {
        Mini_ChocoboBindAnimation(0, *(int *)((char *)record->animTable + animIndex * 4), record->player);
        record->prevAnimId = animIndex;
        record->animId = animIndex;
        record->animIndex = record->player->frameCount;
        return 1;
    }
}

