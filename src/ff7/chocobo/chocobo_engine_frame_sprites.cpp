// Splits the supplied animation path, replaces its extension with ".a",
// concatenates drive/directory/base/extension into a local path and compiles the original text to
// that output. On successful compilation loads the binary from disk when g_ChocoboRetailFlag is zero or
// through Anim_LoadBinary with context+0x40 otherwise. Returns zero on compile failure or the loader
// result; path concatenation uses fixed unchecked buffers.
// FUNCTION: FF7 0x0077a150
int __cdecl Mini_ChocoboCompileAndLoadAnimation(void *context, int srcPath)
{
    struct {
        char prefix[4];
        char part1[256];
        char part2[256];
        char part3[256];
        char path[256];
        int result;
    } frame; /* Stack frame layout: see FRAME UNION in lib/codegen.h. */

    frame.result = 0;
    _splitpath((const char *)srcPath, frame.prefix, frame.part2, frame.part1, frame.part3);
    // STRING: FF7 0x00980da0
    strcpy(frame.part3, (char *)(int)".a");
    strcpy(frame.path, frame.prefix);
    strcat(frame.path, frame.part2);
    strcat(frame.path, frame.part1);
    strcat(frame.path, frame.part3);
    if (Anim_CompileTextToBinary(srcPath, (int)frame.path) != 0) {
        if (g_ChocoboRetailFlag == 0) {
            frame.result = ((int (__cdecl *)(int))Anim_LoadBinaryFromDisk)((int)frame.path); /* reads eax after a void call, as the original does */
        } else {
            frame.result = Anim_LoadBinary((FileOpenRequest *)((char *)context + 0x40), (int)frame.path);
        }
    }
    return frame.result;
}
