// Measures timestamp elapsed from the frame start and busy-waits to the target frame duration.
// When a non-delayed frame is already late, stores its excess and marks delay; the following
// delayed frame waits against duration minus that excess and clears delay/excess. `context` is unused.
// FUNCTION: FF7 0x00779cc6
void __cdecl Mini_ChocoboWaitFrameSlice(struct GfxEngineContext *context)
{
    double elapsed;
    int delta[2];

    elapsed = 0.0;
    ReadTimestampCounter(&g_ChocoboTimestampNow);
    Sub64(&g_ChocoboTimestampNow, &g_ChocoboFrameStartTimestamp, (struct Timestamp64 *)delta);
    elapsed = CombineSplitValueToFloat((struct Timestamp64 *)delta);
    if (g_ChocoboFrameLate == 0) {
        if (elapsed <= g_ChocoboFrameDuration) {
            while (elapsed < g_ChocoboFrameDuration) {
                ReadTimestampCounter(&g_ChocoboTimestampNow);
                Sub64(&g_ChocoboTimestampNow, &g_ChocoboFrameStartTimestamp, (struct Timestamp64 *)delta);
                elapsed = CombineSplitValueToFloat((struct Timestamp64 *)delta);
            }
            g_ChocoboFrameLate = 0;
            ((int *)&g_ChocoboFrameTimeAccum)[0] = 0;
            ((int *)&g_ChocoboFrameTimeAccum)[1] = 0;
        } else {
            g_ChocoboFrameTimeAccum = elapsed - g_ChocoboFrameDuration;
            g_ChocoboFrameLate = 1;
        }
    } else {
        while (g_ChocoboFrameDuration - g_ChocoboFrameTimeAccum > elapsed) {
            ReadTimestampCounter(&g_ChocoboTimestampNow);
            Sub64(&g_ChocoboTimestampNow, &g_ChocoboFrameStartTimestamp, (struct Timestamp64 *)delta);
            elapsed = CombineSplitValueToFloat((struct Timestamp64 *)delta);
        }
        g_ChocoboFrameLate = 0;
        ((int *)&g_ChocoboFrameTimeAccum)[0] = 0;
        ((int *)&g_ChocoboFrameTimeAccum)[1] = 0;
    }
}
/* Ends a race frame: holds it to 30 fps and catches up after a late one. Called by
   Mini_ChocoboFrame (and Mini_ChocoboStepFrame) after the state machine ran and drew.
   g_ChocoboFramePacingOn, set on entry, turns pacing on; with it clear only the end-of-frame
   reset runs. g_ChocoboFrameLate is the late flag Mini_ChocoboWaitFrameSlice sets when a frame
   overran; while it is set Mini_ChocoboDrawFrame skips drawing, so that frame was logic only.
   With pacing on:
   - not late: busy-waits the rest of the frame slice;
   - late: waits the slice minus the overrun, clears the flag, resets the per-frame draw state,
     the racers' drawPending flags and the input latches, adds 1 to the context's tickCount,
     zeroes the frame start time and runs one extra step through Mini_ChocoboStepFrame (input,
     state machine, nested tick); returns at once if that step set g_ChocoboExitFlag, otherwise
     waits the slice again.
   Last, resets the per-frame draw state, the racers' drawPending flags and the input latches and
   zeroes g_ChocoboFrameStartTimestamp. */
// FUNCTION: FF7 0x00779e14
void __cdecl Mini_ChocoboTick(struct GfxEngineContext *context)
{
    int i;

    g_ChocoboTickFlag = 0;
    if (g_ChocoboFramePacingOn == 0) {
        Mini_ChocoboDebugOverlayNoOp(context);
    } else {
        if (g_ChocoboFrameLate == 0) {
            Mini_ChocoboDebugOverlayNoOp(context);
            g_ChocoboFrameLate = 0;
        } else {
            Mini_ChocoboWaitFrameSlice(context);
            g_ChocoboFrameLate = 0;
            Mini_ChocoboResetPerFrameDrawState(context);
            for (i = 0; i < (*(unsigned short *)&g_ChocoboRacerCounts); i++) {
                g_pChocoboRacerTable[i].drawPending = 0;
            }
            Mini_ChocoboClearInputLatches();
            context->framesThisSecond += 1.0;
            g_ChocoboFrameStartTimestamp.lo = 0;
            Mini_ChocoboStepFrame(context);
            if (g_ChocoboExitFlag != 0) {
                return;
            }
            Mini_ChocoboDebugOverlayNoOp(context);
        }
        Mini_ChocoboWaitFrameSlice(context);
    }
    Mini_ChocoboResetPerFrameDrawState(context);
    for (i = 0; i < (*(unsigned short *)&g_ChocoboRacerCounts); i++) {
        g_pChocoboRacerTable[i].drawPending = 0;
    }
    Mini_ChocoboClearInputLatches();
    g_ChocoboFrameStartTimestamp.lo = 0;
}
