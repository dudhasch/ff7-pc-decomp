// The minigame frame draw. Takes the context from GetEngineContext, stamps entry with
// ReadTimestampCounter, and returns at once if g_ChocoboFrameLate is set. Otherwise Gfx_BeginSceneCall
// and pass 0: with render state 2 off it walks the forty slots of the 0x1C-stride table at
// g_ChocoboHudRenderObjects (renderObj, alternateFlag draw-as-object, activeFlag present, slotUsedFlag dirty, readyFlag late) and
// emits each present, dirty, non-late slot through Gfx_DrawRenderObjectCall or
// Gfx_EmitPrimitiveBatchList; then Menu_EmitFontBatchLists, the three batch lists
// g_ChocoboSubmitTriangleRenderObj/g_ChocoboEmitTriangleRenderObj1/g_ChocoboEmitQuadRenderObj1
// gated on g_ChocoboSubmitTrianglesDirty/g_ChocoboEmitTriangleDirty1/g_ChocoboEmitQuadDirty1,
// Mini_ChocoboEmitSpriteObjectsGroup0, and Anim_DrawSkeletonFrame for every entry of the
// g_ChocoboRacerCounts-long array g_pChocoboRacerTable with drawPending set and additive
// clear. Pass 1 repeats it for the late half: g_ChocoboEmitTriangleRenderObj2 and
// g_ChocoboEmitQuadRenderObj2, the object g_ChocoboHudObj when g_ChocoboUiContext and
// g_ChocoboHudObjDirty are both set, Mini_ChocoboEmitSpriteObjectsGroup1, the slots with readyFlag non-
// zero and the skeletons with additive non-zero. Closes with Gfx_EndSceneCall and, when
// context->statsRecord is non-null, Sub64 of the two timestamps into its timeA.
// FUNCTION: FF7 0x0077b2ca
void __cdecl Mini_ChocoboDrawFrame(void)
{
    struct Timestamp64 endTime;
    GfxEngineContext *pEngine;
    unsigned short slotIndex;
    struct Timestamp64 startStamp;

    pEngine = GetEngineContext();
    ReadTimestampCounter(&startStamp);
    if (g_ChocoboFrameLate != 0) {
        return;
    }
    Gfx_BeginSceneCall(0, pEngine);
    Gfx_SetScenePassCall(GFX_SCENE_PASS_OPAQUE, (struct GfxEngineContext *)((int)pEngine));
    Gfx_SetRenderStateCall(RENDER_STATE_LINEAR_FILTER, 0, (struct GfxEngineContext *)((int)pEngine));
    for (slotIndex = 0; slotIndex < 0x28; slotIndex++) {
        if (g_ChocoboHudRenderObjects[slotIndex].activeFlag != 0 && g_ChocoboHudRenderObjects[slotIndex].slotUsedFlag != 0 && g_ChocoboHudRenderObjects[slotIndex].readyFlag == 0) {
            if (g_ChocoboHudRenderObjects[slotIndex].alternateFlag != 0) {
                Gfx_DrawRenderObjectCall(g_ChocoboHudRenderObjects[slotIndex].renderObj, pEngine);
            } else {
                Gfx_EmitPrimitiveBatchList(g_ChocoboHudRenderObjects[slotIndex].renderObj, pEngine);
            }
        }
    }
    Menu_EmitFontBatchLists(pEngine);
    if (g_ChocoboSubmitTrianglesDirty != 0) {
        Gfx_EmitPrimitiveBatchList(g_ChocoboSubmitTriangleRenderObj, pEngine);
    }
    if (g_ChocoboEmitTriangleDirty1 != 0) {
        Gfx_EmitPrimitiveBatchList(g_ChocoboEmitTriangleRenderObj1, pEngine);
    }
    if (g_ChocoboEmitQuadDirty1 != 0) {
        Gfx_EmitPrimitiveBatchList(g_ChocoboEmitQuadRenderObj1, pEngine);
    }
    Mini_ChocoboEmitSpriteObjectsGroup0(pEngine);
    Gfx_SetRenderStateCall(RENDER_STATE_LINEAR_FILTER, 1, (struct GfxEngineContext *)((int)pEngine));
    for (slotIndex = 0; slotIndex < (*(unsigned short *)&g_ChocoboRacerCounts); slotIndex++) {
        if (g_pChocoboRacerTable[slotIndex].drawPending != 0 && g_pChocoboRacerTable[slotIndex].additive == 0) {
            Anim_DrawSkeletonFrame(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->model, (PolygonSkeletonAnim *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->skeletonAnim), (PolygonBoneTransform *)(g_pChocoboRacerTable[slotIndex].animPlayer + 0x38), (PolygonAnimDraw *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->animDraw), (GfxEngineContext *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->engineContext));
        }
    }
    Gfx_SetScenePassCall(GFX_SCENE_PASS_TRANSLUCENT, (struct GfxEngineContext *)((int)pEngine));
    Gfx_SetRenderStateCall(RENDER_STATE_LINEAR_FILTER, 0, (struct GfxEngineContext *)((int)pEngine));
    if (g_ChocoboEmitTriangleDirty2 != 0) {
        Gfx_EmitPrimitiveBatchList(g_ChocoboEmitTriangleRenderObj2, pEngine);
    }
    if (g_ChocoboEmitQuadDirty2 != 0) {
        Gfx_EmitPrimitiveBatchList(g_ChocoboEmitQuadRenderObj2, pEngine);
    }
    if (g_ChocoboUiContext != 0 && g_ChocoboHudObjDirty != 0) {
        Gfx_DrawRenderObjectCall((GfxRenderObject *)g_ChocoboHudObj, pEngine);
    }
    Mini_ChocoboEmitSpriteObjectsGroup1(pEngine);
    for (slotIndex = 0; slotIndex < 0x28; slotIndex++) {
        if (g_ChocoboHudRenderObjects[slotIndex].activeFlag != 0 && g_ChocoboHudRenderObjects[slotIndex].slotUsedFlag != 0 && g_ChocoboHudRenderObjects[slotIndex].readyFlag != 0) {
            if (g_ChocoboHudRenderObjects[slotIndex].alternateFlag != 0) {
                Gfx_DrawRenderObjectCall(g_ChocoboHudRenderObjects[slotIndex].renderObj, pEngine);
            } else {
                Gfx_EmitPrimitiveBatchList(g_ChocoboHudRenderObjects[slotIndex].renderObj, pEngine);
            }
        }
    }
    Gfx_SetRenderStateCall(RENDER_STATE_LINEAR_FILTER, 1, (struct GfxEngineContext *)((int)pEngine));
    for (slotIndex = 0; slotIndex < (*(unsigned short *)&g_ChocoboRacerCounts); slotIndex++) {
        if (g_pChocoboRacerTable[slotIndex].drawPending != 0 && g_pChocoboRacerTable[slotIndex].additive != 0) {
            Anim_DrawSkeletonFrame(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->model, (PolygonSkeletonAnim *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->skeletonAnim), (PolygonBoneTransform *)(g_pChocoboRacerTable[slotIndex].animPlayer + 0x38), (PolygonAnimDraw *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->animDraw), (GfxEngineContext *)(((ChocoboRacerModelRecord *)(g_pChocoboRacerTable[slotIndex].animPlayer))->engineContext));
        }
    }
    Gfx_EndSceneCall(pEngine);
    ReadTimestampCounter(&endTime);
    if (pEngine->statsRecord != 0) {
        Sub64(&endTime, &startStamp, &pEngine->statsRecord->timeA);
    }
}

// Syncs a display entry to its player object when animSelectFlag is set; a zero flag does nothing.
// dirty is set to 1 before and after the update. The unsigned-short value is passed to
// Mini_ChocoboSelectAnimationIndex, and the player's activeA, activeB and activeC are set to 1. The
// player's frame index is the lesser of the entry's position and animIndex minus one, with no lower
// clamp. yaw is converted to degrees by multiplying by 360/250, and the heading is its negative,
// plus 180 when uploaded is set. Rotation X is zero and rotation Z is fixed at -180. posX and posZ
// are copied as floats, and posY is copied or, when noGroundOffset is zero, has 10 subtracted.
// FUNCTION: FF7 0x0077b7e2
void __cdecl Mini_ChocoboSyncDisplayEntryToObject(ChocoboRacerEntry *entry)
{
    int padSlot[16]; /* Unreferenced stack padding preserved for VC5 /Od frame size (see lib/codegen.h). */
    int padWord[84]; /* Unreferenced stack padding preserved for VC5 /Od frame size (see lib/codegen.h). */
    float yawDegrees;

    if (entry->syncEnabled != 0) {
        entry->drawPending = 1;
        Mini_ChocoboSelectAnimationIndex(entry, *(unsigned short *)&entry->animId);
        entry->player->isActive = 1;
        entry->player->isPlaying = 1;
        entry->player->holdLastFrame = 1;
        if (entry->position >= entry->animIndex) {
            entry->player->frame = entry->animIndex - 1;
        } else {
            entry->player->frame = entry->position;
        }
        yawDegrees = (float)*(unsigned char *)&entry->yaw * 3.6e+02f / 2.5e+02f;
        entry->player->rotationX = 0;
        if (entry->headingFlipped == 0) {
            entry->player->rotationY = -yawDegrees;
        } else {
            entry->player->rotationY = -yawDegrees + 1.8e+02f;
        }
        entry->player->rotationZ = 0xC3340000;
        entry->player->posX = (float)entry->posX;
        if (entry->noGroundOffset != 0) {
            entry->player->posY = (float)entry->posY;
        } else {
            entry->player->posY = (float)(entry->posY - 0xA);
        }
        entry->player->posZ = (float)entry->posZ;
        entry->drawPending = 1;
    }
}
