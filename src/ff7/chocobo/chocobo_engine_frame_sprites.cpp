// Makes sure a chocobo entity has its skeleton player. Returns 0 for a null entity. For a nonnull
// entity whose animPlayer is absent, it initializes a native load-options block, sets its blend
// mode to blendMode, and calls Skel_LoadHrcAndCreatePlayer with modelName, zero, the entity, the
// options and the context. A nonzero returned handle is stored in animPlayer. Returns 1 for every
// nonnull entity, even when loading fails or an existing handle skips the load.
// FUNCTION: FF7 0x00779ff8
int __cdecl Mini_ChocoboLoadEntitySkeletonIfAbsent(struct GfxEngineContext *context, void *entity, int blendMode)
{
    AnimPlayerInstance *player;
    int bits;
    PfileLoadOptions *optionsPtr;
    PfileLoadOptions pfileOpts;
    int modelName;

    if (entity == 0) {
        return 0;
    } else {
        player = (AnimPlayerInstance *)(((ChocoboEntityRecord *)entity)->animPlayer);
        if (player == 0) {
            optionsPtr = &pfileOpts;
            Pfile_InitLoadOptions((struct PfileLoadOptions *)((int)optionsPtr));
            Pfile_SetLoadOptionsBlendMode(blendMode, (struct PfileLoadOptions *)((int)optionsPtr));
            bits = 0;
            modelName = ((ChocoboEntityRecord *)entity)->modelName;
            player = (AnimPlayerInstance *)Skel_LoadHrcAndCreatePlayer(modelName, bits, (PolygonSkeletonLoadSpec *)entity, (int)optionsPtr, context);
            if (player != 0) {
                ((ChocoboEntityRecord *)entity)->animPlayer = (int)player;
            }
        }
        return 1;
    }
}
/* Loads the skeleton hierarchy named by hrcName and attaches it. Reads g_ChocoboRetailFlag to choose the source: zero means Skel_LoadHrcFromDisk(0, hrcName), non-zero means Skel_LoadHrc(context + 0x40, 0, hrcName), so context+0x40 is the already-resident archive or context. On a non-null hierarchy it calls Skel_BuildHierarchyAndLoadParts(entity, hrc, context, loadFlags) then Skel_SetPartsVisible(1, hrc). Returns the hierarchy pointer, or 0 if the load failed. */
// FUNCTION: FF7 0x0077a092
int __cdecl Mini_ChocoboLoadHrcAndAttach(int hrcName, int entity, int context, struct GfxEngineContext *engine)
{
    PolygonSkelHierarchy *hrc;
    int zero;

    zero = 0;
    if (g_ChocoboRetailFlag == 0) {
        hrc = (PolygonSkelHierarchy *)Skel_LoadHrcFromDisk(zero, hrcName);
    } else {
        hrc = (PolygonSkelHierarchy *)Skel_LoadHrc(context + 0x40, zero, hrcName);
    }
    if (hrc != 0) {
        Skel_BuildHierarchyAndLoadParts(entity, hrc, (struct PfileLoadOptions *)context, (int)engine);
        Skel_SetPartsVisible(1, hrc);
    }
    return (int)hrc;
}
