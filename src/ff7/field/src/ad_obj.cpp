// Frees any previous g_FieldModelsData and allocates count model records of 0x288C bytes there.
// Returns 0 when the allocation fails and 1 otherwise. The count is masked to 16 bits. Each record
// has its four name bytes, name[0], clearedBuf[0], hrcPath[0] and scaleText[0], zeroed, along with clearedBytesA[0], clearedBytesB[0], ambient[0],
// lightColor[0][0], lightDir[0][0], attribute, clearedWord, animCount, anims[0].name[0] and animAttribute[0].
// FUNCTION: FF7 0x0063cd40
int __cdecl Field_AllocModelDefs(int count)
{
    unsigned short index;

    if (g_FieldModelsData != 0) {
        GameHeapFree(g_FieldModelsData, AdObjCpp_FileLine358(), 0x358);
        g_FieldModelsData = 0;
    }
    g_FieldModelsData = (FieldModelDef *)GameHeapAllocRaw((count & 0xFFFF) * 0x288C, AdObjCpp_FileLine35C(), 0x35C);
    if (g_FieldModelsData == 0) {
        return 0;
    } else {
        for (index = 0; index < (count & 0xFFFF); index++) {
            g_FieldModelsData[index].name[0] = 0;
            g_FieldModelsData[index].clearedBuf[0] = 0;
            g_FieldModelsData[index].hrcPath[0] = 0;
            g_FieldModelsData[index].scaleText[0] = 0;
            g_FieldModelsData[index].clearedBytesA[0] = 0;
            g_FieldModelsData[index].clearedBytesB[0] = 0;
            g_FieldModelsData[index].ambient[0] = 0;
            g_FieldModelsData[index].lightColor[0][0] = 0;
            g_FieldModelsData[index].lightDir[0][0] = 0;
            g_FieldModelsData[index].attribute = 0;
            g_FieldModelsData[index].clearedWord = 0;
            g_FieldModelsData[index].animCount = 0;
            g_FieldModelsData[index].anims[0].name[0] = 0;
            g_FieldModelsData[index].animAttribute[0] = 0;
        }
        return 1;
    }
}

