/*
 * Resolves the full file path for a field model asset.
 */
// FUNCTION: FF7 0x0063de51
void __cdecl Field_ResolveModelFilePath(char *name)
{
    char pathBuf[256];
    unsigned short prefixLength;
    unsigned short nameLen;
    unsigned short pos;
    nameLen = strlen(name);
    if (nameLen > 0) {
        strcpy(pathBuf, g_FieldModelDataDir);
        strcat(pathBuf, (char *)g_pFieldModelDefaultCharDir);
        prefixLength = strlen(pathBuf);
        if (name[1] == '1' && name[2] == 'd') {
            if (name[0x11] == 't' && name[0x12] == 'o' && name[0x13] == 'r' && name[0x20] == '\\' && name[0x21] == '\\') {
                for (pos = 33; pos < nameLen - 1; pos++) {
                    name[pos] = name[pos + 1];
                }
                name[nameLen - 1] = 0;
            }
            if (name[0x10] == '\\') {
                for (pos = 16; pos < nameLen; pos++) {
                    pathBuf[prefixLength + pos - 0x10] = name[pos];
                }
                pathBuf[prefixLength + pos - 0x10] = 0;
            } else {
                for (pos = 13; pos < nameLen; pos++) {
                    pathBuf[prefixLength + pos - 0xd] = name[pos];
                }
                pathBuf[prefixLength + pos - 0xd] = 0;
            }
        } else {
            for (pos = 11; pos < nameLen; pos++) {
                pathBuf[prefixLength + pos - 0xb] = name[pos];
            }
            pathBuf[prefixLength + pos - 0xb] = 0;
        }
        strcpy(name, pathBuf);
    }
}

/*
 * Frees the field models: the 0x14 light owners in g_FieldModelLightData, then for each of the
 * g_FieldHumanAnimState.modelListCountCopy records of g_pFieldModelSlots its textured hundred slots, its model
 * (skeleton first), each of its animations and the animation table, and last the record array
 * itself. Every pointer it frees is cleared.
 */
// FUNCTION: FF7 0x0063e1d8
void __cdecl Field_FreeModels(void)
{
    unsigned short modelIndex;
    unsigned short animIndex;

    for (modelIndex = 0; modelIndex < 0x14; modelIndex++) {
        if (g_FieldModelLightData[modelIndex] != 0) {
            Gfx_LightFreeOwner(1, g_FieldModelLightData[modelIndex]);
            g_FieldModelLightData[modelIndex] = 0;
        }
    }
    for (modelIndex = 0; modelIndex < g_FieldHumanAnimState.modelListCountCopy; modelIndex++) {
        if (g_pFieldModelSlots != 0) {
            Field_FreeTexturedHundredSlots((FieldTexturedSlots *)&g_pFieldModelSlots[modelIndex]);
            if (g_pFieldModelSlots[modelIndex].model != 0) {
                if (g_pFieldModelSlots[modelIndex].model->skeleton != 0) {
                    Skel_Free((PolygonSkelHierarchy *)(g_pFieldModelSlots[modelIndex].model->skeleton));
                }
                GameHeapFree(g_pFieldModelSlots[modelIndex].model, AdObjCpp_FileLine545(), 0x545);
                g_pFieldModelSlots[modelIndex].model = 0;
            }
            for (animIndex = 0; animIndex < g_pFieldModelSlots[modelIndex].animationCount; animIndex++) {
                if (g_pFieldModelSlots[modelIndex].animations != 0 && ((void **)g_pFieldModelSlots[modelIndex].animations)[animIndex] != 0) {
                    Anim_Free((PolygonAnimBuffers *)((void **)g_pFieldModelSlots[modelIndex].animations)[animIndex]);
                    ((void **)g_pFieldModelSlots[modelIndex].animations)[animIndex] = 0;
                }
            }
            if (g_pFieldModelSlots[modelIndex].animations != 0) {
                GameHeapFree((void *)g_pFieldModelSlots[modelIndex].animations, AdObjCpp_FileLine553(), 0x553);
                g_pFieldModelSlots[modelIndex].animations = 0;
            }
        }
    }
    if (g_pFieldModelSlots != 0) {
        GameHeapFree(g_pFieldModelSlots, AdObjCpp_FileLine55A(), 0x55A);
        g_pFieldModelSlots = 0;
    }
}

