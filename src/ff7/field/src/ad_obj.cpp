// A typed 0x94-byte element preserves the nested model/name evaluation order;
// flattening both indices into a byte sum changes VC5 register allocation.
typedef struct FieldAnimName {
    unsigned char name[0x94];
} FieldAnimName;
/* One field model definition (0x288C bytes; Field_AllocModelDefs allocates g_FieldModelsData as
 * an array of them, Field_LoadModelDefs* fill them from the map's model list): the model's name,
 * its skeleton (.hrc) path and scale, three directional lights and an ambient colour, and its
 * animations. */
typedef struct FieldModelDef {
    char name[0x100]; /* +0x000 */
    char clearedBuf[0x100]; /* +0x100: cleared, not read here */
    char hrcPath[0x100]; /* +0x200 */
    char scaleText[0x21]; /* +0x300: four bytes read, then atoi */
    unsigned char clearedBytesA[3];
    unsigned char clearedBytesB[3];
    unsigned char ambient[3]; /* +0x327: r, g, b */
    unsigned char lightColor[3][3]; /* +0x32A: r, g, b of lights 0..2 */
    unsigned char pad_333;
    short lightDir[3][3]; /* +0x334: x, y, z of lights 0..2, 4096 = 1.0 */
    short attribute; /* +0x346 */
    short clearedWord;
    short animCount; // +0x34A
    FieldAnimName anims[64]; // +0x34C
    /* +0x284C: one per animation; the loaders read a u16 at each byte offset, so each read's high
     * byte is overwritten by the next one's low byte */
    unsigned char animAttribute[0x40];
} FieldModelDef;

