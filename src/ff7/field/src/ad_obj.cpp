/*
 * Generates a batch rename script from short and long model name list files.
 */
// FUNCTION: FF7 0x0063cfd0
void __cdecl Field_WriteRenameScriptFromNameLists(void)
{
    FILE *pShortNames;
    char textBuf[256];
    FILE *pFpLong;
    int lineNo;
    FILE *renameFile;
    char cmdBuf[256];
    int charIndex;
    char baseName[256];
    int len;
    int slashPos;
    pShortNames = Field_FileOpen(AdObj_ShortTxtName(), AdObj_ShortTxtMode());
    pFpLong = Field_FileOpen(AdObj_LongTxtName(), AdObj_LongTxtMode());
    renameFile = Field_FileOpen(AdObj_RenameTxtName(), AdObj_RenameTxtMode());
    for (lineNo = 0; lineNo < 18763; lineNo++) {
        // The comma expression preserves VC5's runtime intrinsic scan;
        // a bare literal is folded into fixed moves absent from the original.
        strcpy(cmdBuf, AdObj_RenCommand());
        textBuf[0] = 0;
        fgets(textBuf, 0x7f, pShortNames);
        if (strlen(textBuf) != 0 && textBuf[strlen(textBuf) - 1] == '\n') {
            textBuf[strlen(textBuf) - 1] = 0;
        }
        strcat(cmdBuf, textBuf);
        strcat(cmdBuf, AdObj_RenSeparator());
        textBuf[0] = 0;
        fgets(textBuf, 0x7f, pFpLong);
        textBuf[strlen(textBuf) - 1] = 0;
        if (strlen(textBuf) != 0 && textBuf[strlen(textBuf) - 1] == '\n') {
            textBuf[strlen(textBuf) - 1] = 0;
        }
        len = slashPos = strlen(textBuf);
        slashPos--;
        while (textBuf[slashPos] != '\\') {
            slashPos--;
        }
        for (charIndex = slashPos + 1; charIndex < len; charIndex++) {
            baseName[charIndex - slashPos - 1] = textBuf[charIndex];
        }
        baseName[charIndex - slashPos - 1] = 0;
        strcat(cmdBuf, baseName);
        strcat(cmdBuf, AdObj_RenNewline());
        Field_FileWrite(renameFile, cmdBuf, strlen(cmdBuf));
    }
    Field_FileClose(renameFile);
    Field_FileClose(pShortNames);
    Field_FileClose(pFpLong);
}

