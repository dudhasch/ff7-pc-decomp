int g_BlendRecordCounts[6] = {2, 3, 1, 1, 0, 0};
// Each entry points at the blend records for that blend mode (0 for modes without any).
// GLOBAL: FF7 0x009197e8
void * g_BlendRecordTables[6] = {(void *)g_GfxDefaultBlendRecords, (void *)(g_GfxDefaultBlendRecords + 0x48), (void *)(g_GfxDefaultBlendRecords + 0xb8), (void *)(g_GfxDefaultBlendRecords + 0xe0), 0, 0};
